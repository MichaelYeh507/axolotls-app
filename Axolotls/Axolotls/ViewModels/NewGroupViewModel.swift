import Foundation
import Observation
import FirebaseFirestore

@Observable
final class NewGroupViewModel {
    var name: String = ""
    var description: String = ""
    var mode: String = ""
    var revealAt: Date = Date().addingTimeInterval(86400) // Default to tomorrow
    
    var isSaving = false
    var errorMessage: String?
    
    var isValid: Bool {
        !name.trimmingCharacters(in: .whitespaces).isEmpty
    }
    
    @MainActor
    func createGroup(for userID: String?) async -> Bool {
        guard let userID else {
            errorMessage = "You must be signed in to create a group."
            return false
        }
        
        isSaving = true
        errorMessage = nil
        
        do {
            let uniqueCode = try await generateUniqueJoinCode()
            
            let newGroup = Group(
                id: nil, // DocumentID auto-generated by Firestore
                name: name.trimmingCharacters(in: .whitespaces),
                description: description.trimmingCharacters(in: .whitespaces),
                mode: mode,
                createdAt: Date(),
                revealAt: revealAt,
                joinCode: uniqueCode
            )
            
            let groupReference = try Firestore.app
                .collection("groups")
                .addDocument(from: newGroup)
            
            let membership = Membership(
                userId: userID,
                groupId: groupReference.documentID,
                role: "owner",
                membershipStatus: "active",
                joinedAt: Date(),
            )
            try Firestore.app
                .collection("membership")
                .addDocument(from: membership)
            
            isSaving = false
            return true
        } catch {
            isSaving = false
            self.errorMessage = error.localizedDescription
            return false
        }
    }
    
    @MainActor
    func generateUniqueJoinCode() async throws -> String {
        let db = Firestore.app
        var code = ""
        var isUnique = false
        var attempts = 0
        
        while !isUnique && attempts < 10 {
            code = generateJoinCode()
            attempts += 1
            
            // Check if any group already uses this join code
            let snapshot = try await db.collection("groups")
                .whereField("join_code", isEqualTo: code)
                .getDocuments()
            
            if snapshot.documents.isEmpty {
                isUnique = true
            }
        }
        
        guard isUnique else {
            throw NSError(domain: "JoinCodeError", code: 500, userInfo: [NSLocalizedDescriptionKey: "Failed to generate a unique code. Please try again."])
        }
        
        return code
    }
    
    func generateJoinCode(length: Int = 6) -> String {
        let letters = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789" // Excluded easily confused characters like O, 0, I, 1
        return String((0..<length).compactMap { _ in letters.randomElement() })
    }
}
